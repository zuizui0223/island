def _efloras_existing_map(lineages: pd.DataFrame) -> dict[tuple[str, str], tuple[str, str]]:
    source = lineages.loc[lineages["source_provider"].isin({"efloras:1", "efloras:2"})]
    result: dict[tuple[str, str], tuple[str, str]] = {}
    for item in source.sort_values(["source_provider", "accepted_species", "source_url"]).to_dict(
        "records"
    ):
        result.setdefault(
            (_text(item["source_provider"]), _text(item["accepted_species"])),
            (_text(item["source_lineage"]), _text(item["source_url"])),
        )
    return result


def nhm_efloras_rows(root: Path, lineages: pd.DataFrame) -> list[dict[str, str]]:
    known = _efloras_existing_map(lineages)
    rows: list[dict[str, str]] = []
    for slug, metadata in NHM_RESOURCES.items():
        path = root / f"{slug}_exact_master_records.csv.gz"
        source = pd.read_csv(path, dtype=str).fillna("")
        resource_url = (
            "https://data.nhm.ac.uk/dataset/angiosperm-functional-traits-extracted-"
            f"from-botanical-descriptions/resource/{metadata['resource_id']}"
        )
        for item in source.to_dict("records"):
            species = _text(item["taxon"])
            wfo = _text(item.get("wfo"))
            original = known.get((metadata["efloras_provider"], species))
            source_url = original[1] if original else resource_url
            lineage = original[0] if original else f"efloras:{slug}:{wfo.casefold()}"
            lineage_method = (
                "matched_existing_original_efloras_treatment"
                if original
                else "original_flora_species_treatment_via_wfo_id"
            )
            for extracted in _extract_record(item):
                rows.append(
                    _record(
                        species=species,
                        trait=_text(extracted["trait_name"]),
                        axis=_text(extracted["axis"]),
                        value=_text(extracted["normalized_value"]),
                        provider=metadata["provider"],
                        url=source_url,
                        source_key=f"{metadata['resource_id']}:{_text(item['_id'])}",
                        citation=metadata["citation"],
                        excerpt=_text(extracted["source_excerpt"]),
                        lineage=lineage,
                        lineage_method=lineage_method,
                        source_artifact=f"nhm-adept-resource-{metadata['resource_id']}",
                        source_file=path.name,
                    )
                )
    return rows


def _baseflor_colour(value: str) -> str:
    states = {
        COLOUR_MAP[token.strip().casefold()]
        for token in value.split(",")
        if token.strip().casefold() in COLOUR_MAP
    }
    return "|".join(sorted(states))


def _baseflor_inflorescence(value: str) -> str:
    folded = value.casefold()
    states: set[str] = set()
    if "solitaire" in folded:
        states.add("solitary")
    if any(token in folded for token in ("racème", "panicule", "épi")):
        states.add("raceme_spike_panicle")
    if any(token in folded for token in ("cyme", "ombelle", "corymbe")):
        states.add("umbel_corymb")
    if "capitule" in folded or "capituliforme" in folded:
        states.add("composite_display")
    return "|".join(sorted(states))


def baseflor_rows(path: Path, master_names: set[str]) -> list[dict[str, str]]:
    actual_hash = _sha256(path)
    if actual_hash != BASEFLOR_SHA256:
        raise ValueError(f"Baseflor SHA256 {actual_hash} != pinned {BASEFLOR_SHA256}")
    source = pd.read_excel(path, sheet_name="baseflor", dtype=str).fillna("")
    source = source.loc[source["rang_taxinomique"].eq("esp") & source["nomH"].isin(master_names)]
    taxon_column = source.columns[1]
    url = (
        "https://web.archive.org/web/20231002005253id_/"
        "https://philippe.julve.pagesperso-orange.fr/baseflor.xlsx"
    )
    rows: list[dict[str, str]] = []
    for item in source.to_dict("records"):
        species = _text(item["nomH"])
        taxon_id = _text(item[taxon_column])
        lineage = f"baseflor:species:{species.casefold().replace(' ', '_')}"
        common = {
            "species": species,
            "provider": "baseflor_2023_10",
            "url": url,
            "lineage": lineage,
            "lineage_method": "original_baseflor_species_record",
            "source_artifact": f"baseflor-2023-10-sha256-{BASEFLOR_SHA256}",
            "source_file": path.name,
        }
        colour = _baseflor_colour(_text(item["couleur_fleur"]))
        if colour:
            rows.append(
                _record(
                    **common,
                    trait="flower_primary_color",
                    axis="flower_colour",
                    value=colour,
                    source_key=f"{taxon_id}:colour",
                    citation="Julve, Baseflor 2023.10, flower-colour field",
                    excerpt=f"couleur_fleur: {_text(item['couleur_fleur'])}",
                )
            )
        inflorescence = _baseflor_inflorescence(_text(item["inflorescence"]))
        if inflorescence:
            rows.append(
                _record(
                    **common,
                    trait="inflorescence_display",
                    axis="floral_structural_complexity",
                    value=inflorescence,
                    source_key=f"{taxon_id}:inflorescence",
                    citation="Julve, Baseflor 2023.10, inflorescence field",
                    excerpt=f"inflorescence: {_text(item['inflorescence'])}",
                )
            )
        # Baseflor's ``pollinisation`` field describes pollen transfer.  An
        # ``autogame`` token does not establish unassisted fertilisation,
        # fruit set, or seed set, so it cannot populate reproductive assurance.
    return rows


def florabase_rows(path: Path) -> list[dict[str, str]]:
    source = pd.read_csv(path, dtype=str).fillna("")
    source = source.loc[
        source["identity_exact"].str.casefold().eq("true") & source["explicit_colours"].ne("")
    ]
    colour_map = {
        "black": "other_described",
        "blue": "blue_purple",
        "brown": "green_brown_inconspicuous",
        "cream": "white",
        "green": "green_brown_inconspicuous",
        "grey": "other_described",
        "orange": "yellow_orange",
        "pink": "red_pink",
        "purple": "blue_purple",
        "red": "red_pink",
        "violet": "blue_purple",
        "white": "white",
        "yellow": "yellow_orange",
    }
    rows = []
    for item in source.to_dict("records"):
        description = _text(item["supporting_excerpt"])
        flower_clause_match = re.search(r"\bFl\.\s*([^.]*)", description, re.IGNORECASE)
        if not flower_clause_match:
            continue
        flower_clause = flower_clause_match.group(0)
        explicit = [
            token
            for token in _text(item["explicit_colours"]).split("|")
            if re.search(rf"\b{re.escape(token)}(?:ish|y)?\b", flower_clause, re.IGNORECASE)
        ]
        states = {colour_map[token] for token in explicit if token in colour_map}
        if not states:
            continue
        species = _text(item["accepted_species"])
        url = _text(item["profile_url"])
        rows.append(
            _record(
                species=species,
                trait="flower_primary_color",
                axis="flower_colour",
                value="|".join(sorted(states)),
                provider="florabase_western_australia",
                url=url,
                source_key=_text(item["profile_id"]),
                citation="Western Australian Herbarium, FloraBase taxon profile",
                excerpt=flower_clause,
                lineage=f"florabase:profile:{_text(item['profile_id'])}",
                lineage_method="original_florabase_profile_id",
                source_artifact="florabase-live-profile-cache-20260808",
                source_file=path.name,
            )
        )
    return rows


def _floraweb_si(value: str) -> str:
    folded = value.casefold()
    if folded == "selbstkompatibel":
        return "SC"
    if folded == "selbstinkompatibel":
        return "SI"
    if folded in {"± selbstinkompatibel", "± selbstkompatibel"}:
        return "mixed_or_variable"
    return ""


def _floraweb_mating(value: str) -> str:
    return {
        "obligat autogam": "obligate_selfing",
        "fakultativ autogam": "predominantly_selfing",
        "gemischte befruchtung": "mixed_mating",
        "fakultativ xenogam": "predominantly_outcrossing",
        "xenogam": "predominantly_outcrossing",
    }.get(value.casefold(), "")


def _floraweb_form(value: str) -> str:
    folded = value.casefold()
    if "schmetterlingsblumen" in folded or "fabaceentyp" in folded:
        return "papilionaceous"
    if "lippenblumen" in folded:
        return "bilabiate"
    if "stieltellerblumen" in folded:
        return "salverform"
    if "trichterblumen" in folded:
        return "funnel_trumpet"
    if "glockenblumen" in folded:
        return "bell_campanulate"
    if "köpfchenblumen" in folded:
        return "composite_head"
    if "pinsel- und bürstenblumen" in folded:
        return "brush_puff"
    if "violatyp" in folded:
        return "spurred"
    if "scheibenblumen" in folded:
        return "open_radial"
    if any(
        token in folded for token in ("kesselfallenblumen", "klemmfallenblumen", "kolbenblumen")
    ):
        return "other_described"
    return ""


def _floraweb_selfing_trait(value: str) -> tuple[str, str]:
    folded = value.casefold()
    # Pseudocleistogamy is a distinct floral phenomenon and cannot establish
    # presence or absence of true cleistogamy.
    if "pseudokleistogamie" in folded:
        return "", ""
    # BiolFlor section 4.8 records pollen vectors independently from
    # subsequent fertilisation.  Selbstbestäubung therefore cannot establish
    # autonomous reproductive output (including delayed or absent output).
    if "selbstbestäubung" in folded:
        return "", ""
    if "kleistogamie" in folded:
        if folded.startswith("nie "):
            return "cleistogamy", "absent"
        if folded.startswith("unbekannt "):
            return "", ""
        return "cleistogamy", "facultative"
    return "", ""


def floraweb_rows(
    path: Path, eligible_names: set[str]
) -> tuple[list[dict[str, str]], list[dict[str, str]]]:
    actual_hash = _sha256(path)
    if actual_hash != FLORAWEB_SHA256:
        raise ValueError(f"FloraWeb SHA256 {actual_hash} != pinned {FLORAWEB_SHA256}")
    source = pd.read_csv(path, dtype=str).fillna("")
    source = source.loc[source["canonical_name"].isin(eligible_names)].copy()
    strict_rows: list[dict[str, str]] = []
    non_axis_by_species: dict[tuple[str, str], set[str]] = {}
    source_ids: dict[str, str] = {}
    raw_values: dict[tuple[str, str], list[str]] = {}
    for item in source.to_dict("records"):
        species = _text(item["canonical_name"])
        usage_id = _text(item["name_usage_id"])
        label = _text(item["label"])
        raw = _text(item["value"])
        source_ids[species] = usage_id
        source_url = f"https://www.floraweb.de/php/biologie.php?suchnr={usage_id}&"
        common = {
            "species": species,
            "provider": "floraweb_biolflor_snapshot_2026_06_24",
            "url": source_url,
            "lineage": f"floraweb:name_usage_id:{usage_id}",
            "lineage_method": "original_floraweb_name_usage_id",
            "source_artifact": f"taxifydb-floraweb-raw-2026-06-24-sha256-{FLORAWEB_SHA256}",
            "source_file": path.name,
            "quality": "medium",
        }
        trait = ""
        axis = ""
        value = ""
        if label == "SI-Reaktion":
            trait, axis, value = (
                "self_incompatibility",
                "reproductive_assurance",
                _floraweb_si(raw),
            )
        elif label == "Befruchtungstyp":
            trait, axis, value = (
                "mating_system",
                "reproductive_assurance",
                _floraweb_mating(raw),
            )
        elif label == "Blumentyp (nach Kugler 1970)":
            trait, axis, value = (
                "floral_form",
                "floral_structural_complexity",
                _floraweb_form(raw),
            )
        elif label == "Bestäubung (Pollenvektoren)":
            trait, value = _floraweb_selfing_trait(raw)
            axis = "reproductive_assurance" if trait else ""
            folded = raw.casefold()
            if not folded.startswith(("nie ", "unbekannt ")):
                key = (species, "pollen_vector_mode")
                if "insektenbestäubung" in folded:
                    non_axis_by_species.setdefault(key, set()).add("biotic")
                    raw_values.setdefault(key, []).append(raw)
                if "windbestäubung" in folded:
                    non_axis_by_species.setdefault(key, set()).add("abiotic_wind")
                    raw_values.setdefault(key, []).append(raw)
        elif label == "Belohnung für Bestäuber":
            folded = raw.casefold()
            key = (species, "reward_type")
            if "nektar" in folded and not folded.startswith("kein "):
                non_axis_by_species.setdefault(key, set()).add("nectar")
                raw_values.setdefault(key, []).append(raw)
            if "pollen" in folded and not folded.startswith("kein "):
                non_axis_by_species.setdefault(key, set()).add("pollen")
                raw_values.setdefault(key, []).append(raw)
            if "öl" in folded and not folded.startswith("kein "):
                non_axis_by_species.setdefault(key, set()).add("oil")
                raw_values.setdefault(key, []).append(raw)
        if value:
            strict_rows.append(
                _record(
                    **common,
                    trait=trait,
                    axis=axis,
                    value=value,
                    source_key=f"{usage_id}:{label}:{raw}",
                    citation=(
                        "FloraWeb (Bundesamt für Naturschutz), carrying BiolFlor "
                        "traits of Klotz, Kühn & Durka (2002); archived snapshot 2026-06-24"
                    ),
                    excerpt=f"{label}: {raw}",
                )
            )

    supplemental: list[dict[str, str]] = []
    for (species, trait), states in sorted(non_axis_by_species.items()):
        value = (
            "mixed"
            if trait == "pollen_vector_mode" and len(states) > 1
            else "|".join(sorted(states))
        )
        usage_id = source_ids[species]
        supplemental.append(
            _record(
                species=species,
                trait=trait,
                axis="",
                value=value,
                provider="floraweb_biolflor_snapshot_2026_06_24",
                url=f"https://www.floraweb.de/php/biologie.php?suchnr={usage_id}&",
                source_key=f"{usage_id}:{trait}",
                citation=(
                    "FloraWeb (Bundesamt für Naturschutz), carrying BiolFlor "
                    "traits of Klotz, Kühn & Durka (2002); archived snapshot 2026-06-24"
                ),
                excerpt="; ".join(sorted(set(raw_values[(species, trait)]))),
                lineage=f"floraweb:name_usage_id:{usage_id}",
                lineage_method="original_floraweb_name_usage_id",
                source_artifact=f"taxifydb-floraweb-raw-2026-06-24-sha256-{FLORAWEB_SHA256}",
                source_file=path.name,
                quality="medium",
            )
        )
    return strict_rows, supplemental


def _require_hash(path: Path, expected: str, label: str) -> None:
    actual = _sha256(path)
    if actual != expected:
        raise ValueError(f"{label} SHA256 {actual} != pinned {expected}")


