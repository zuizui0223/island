def direct_literature_rows(path: Path, eligible_names: set[str]) -> list[dict[str, str]]:
    source = pd.read_csv(path, dtype=str).fillna("")
    required = {
        "accepted_species",
        "trait_name",
        "axis",
        "normalized_value",
        "quality",
        "source_url",
        "source_citation",
        "source_excerpt",
        "name_match_method",
        "source_lineage",
        "lineage_method",
        "source_artifact",
        "source_file",
    }
    missing = required - set(source.columns)
    if missing:
        raise ValueError(f"direct literature manifest missing columns: {sorted(missing)}")
    source = source.loc[source["accepted_species"].isin(eligible_names)].copy()
    rows: list[dict[str, str]] = []
    for item in source.to_dict("records"):
        species = _text(item["accepted_species"])
        rows.append(
            _record(
                species=species,
                trait=_text(item["trait_name"]),
                axis=_text(item["axis"]),
                value=_text(item["normalized_value"]),
                provider="direct_reproductive_literature_20260808",
                url=_text(item["source_url"]),
                source_key=f"{species}:{_text(item['source_lineage'])}",
                citation=_text(item["source_citation"]),
                excerpt=_text(item["source_excerpt"]),
                lineage=_text(item["source_lineage"]),
                lineage_method=_text(item["lineage_method"]),
                source_artifact=_text(item["source_artifact"]),
                source_file=_text(item["source_file"]),
                quality=_text(item["quality"]),
                name_match_method=_text(item["name_match_method"]),
                evidence_scope=(
                    "synonym_direct"
                    if _text(item["name_match_method"]).startswith("synonym_")
                    else "species_direct"
                ),
                acceptance_contract="quoted_original_reproductive_study_v1",
            )
        )
    return rows


def _sample_provider(evidence: pd.DataFrame, target: int = 200) -> pd.DataFrame:
    if len(evidence) <= target:
        return evidence.copy()
    pieces = []
    groups = list(evidence.groupby("trait_name", sort=True))
    remaining = target
    for index, (_, group) in enumerate(groups):
        if index == len(groups) - 1:
            take = min(remaining, len(group))
        else:
            take = min(len(group), max(10, round(target * len(group) / len(evidence))))
            take = min(take, remaining - 10 * (len(groups) - index - 1))
        pieces.append(group.sample(n=take, random_state=AUDIT_RANDOM_STATE + index))
        remaining -= take
    if remaining:
        used = set(pd.concat(pieces)["source_record_id"])
        rest = evidence.loc[~evidence["source_record_id"].isin(used)]
        pieces.append(
            rest.sample(n=min(remaining, len(rest)), random_state=AUDIT_RANDOM_STATE + 99)
        )
    return pd.concat(pieces, ignore_index=True)


def build(
    *,
    grassbase_csv: Path,
    nhm_root: Path,
    baseflor_xlsx: Path,
    florabase_csv: Path,
    floraweb_csv: Path,
    pfaf_csv: Path,
    ken_fern_csv: Path,
    tree_of_sex_csv: Path,
    alien_plants_autogamy_html: Path,
    direct_literature_csv: Path,
    master_csv: Path,
    current_coverage_csv: Path,
    current_lineages_csv: Path,
    output_dir: Path,
) -> dict[str, object]:
    master = pd.read_csv(master_csv, dtype=str).fillna("")
    master_names = set(master["accepted_species"])
    coverage = pd.read_csv(current_coverage_csv, usecols=["accepted_species"], dtype=str).fillna("")
    strict_names = set(coverage["accepted_species"])
    if len(strict_names) != 106_295:
        raise ValueError(f"strict coverage has {len(strict_names)} species, expected 106295")
    eligible_names = master_names & strict_names
    lineages = pd.read_csv(current_lineages_csv, dtype=str).fillna("")
    current_pairs = _current_pairs(lineages)
    floraweb_strict, supplemental = floraweb_rows(floraweb_csv, eligible_names)
    records = (
        grassbase_rows(grassbase_csv)
        + nhm_efloras_rows(nhm_root, lineages)
        + baseflor_rows(baseflor_xlsx, eligible_names)
        + florabase_rows(florabase_csv)
        + floraweb_strict
        + pfaf_rows(pfaf_csv)
        + ken_fern_rows(ken_fern_csv)
        + tree_of_sex_rows(tree_of_sex_csv, master)
        + alien_plants_autogamy_rows(alien_plants_autogamy_html, eligible_names)
        + direct_literature_rows(direct_literature_csv, eligible_names)
    )
    inventory = pd.DataFrame(records, columns=EVIDENCE_COLUMNS).fillna("")
    inventory = inventory.loc[inventory["accepted_species"].isin(eligible_names)].copy()
    inventory = inventory.drop_duplicates(
        ["accepted_species", "trait_name", "normalized_value", "source_lineage"]
    ).sort_values(["source_provider", "trait_name", "accepted_species", "source_record_id"])
    inventory["novel_species_trait"] = [
        (species, trait) not in current_pairs
        for species, trait in zip(
            inventory["accepted_species"], inventory["trait_name"], strict=True
        )
    ]
    evidence = (
        inventory.loc[inventory["novel_species_trait"]]
        .drop(columns="novel_species_trait")
        .reset_index(drop=True)
    )
    if evidence["source_record_id"].duplicated().any():
        raise ValueError("source_record_id is not unique")

    audit_parts = []
    for provider, group in evidence.groupby("source_provider", sort=True):
        sampled = _sample_provider(group, target=200)
        sampled = sampled.rename(
            columns={
                "source_provider": "provider",
                "source_record_id": "candidate_id",
                "source_excerpt": "exact_supporting_quote",
            }
        )
        sampled["accepted_correct"] = ""
        sampled["cultivar_status"] = "wild_or_unspecified_species_record"
        sampled["reviewer"] = ""
        sampled["reviewed_at_utc"] = ""
        sampled["audit_reason"] = ""
        audit_parts.append(sampled)
    audit = pd.concat(audit_parts, ignore_index=True).sort_values(
        ["provider", "trait_name", "accepted_species", "candidate_id"]
    )

    output_dir.mkdir(parents=True, exist_ok=True)
    inventory.to_csv(output_dir / "scale_source_full_inventory.csv.gz", index=False)
    evidence.to_csv(output_dir / "scale_source_incremental_evidence.csv.gz", index=False)
    audit.to_csv(output_dir / "scale_source_manual_audit.csv", index=False)
    pd.DataFrame(supplemental, columns=EVIDENCE_COLUMNS).to_csv(
        output_dir / "scale_source_non_axis_candidates.csv.gz", index=False
    )

    provider_rows = []
    for provider, group in evidence.groupby("source_provider", sort=True):
        provider_rows.append(
            {
                "source_provider": provider,
                "evidence_rows": len(group),
                "species": int(group["accepted_species"].nunique()),
                "species_trait": len(group.drop_duplicates(["accepted_species", "trait_name"])),
                "traits": sorted(group["trait_name"].unique()),
                "audit_rows": int(audit["provider"].eq(provider).sum()),
            }
        )
    summary: dict[str, object] = {
        "contract": "scale_structured_flora_source_package_v1",
        "created_at_utc": datetime.now(timezone.utc).isoformat(),  # noqa: UP017
        "current_direct_species_trait": len(current_pairs),
        "strict_universe_species": len(strict_names),
        "full_inventory_rows": len(inventory),
        "full_inventory_species_trait": len(
            inventory.drop_duplicates(["accepted_species", "trait_name"])
        ),
        "incremental_evidence_rows": len(evidence),
        "incremental_species_trait": len(
            evidence.drop_duplicates(["accepted_species", "trait_name"])
        ),
        "incremental_species": int(evidence["accepted_species"].nunique()),
        "non_axis_candidate_rows": len(supplemental),
        "audit_rows": len(audit),
        "providers": provider_rows,
        "baseflor_sha256": BASEFLOR_SHA256,
        "input_files": {
            f"grassbase/{grassbase_csv.name}": {"sha256": _sha256(grassbase_csv)},
            **{
                path.name: {"sha256": _sha256(path)}
                for path in sorted(nhm_root.glob("*_exact_master_records.csv.gz"))
            },
            f"baseflor/{baseflor_xlsx.name}": {"sha256": _sha256(baseflor_xlsx)},
            f"florabase/{florabase_csv.name}": {"sha256": _sha256(florabase_csv)},
            f"floraweb/{floraweb_csv.name}": {"sha256": _sha256(floraweb_csv)},
            f"pfaf/{pfaf_csv.name}": {"sha256": _sha256(pfaf_csv)},
            f"ken_fern/{ken_fern_csv.name}": {"sha256": _sha256(ken_fern_csv)},
            f"tree_of_sex/{tree_of_sex_csv.name}": {"sha256": _sha256(tree_of_sex_csv)},
            f"alien_plants/{alien_plants_autogamy_html.name}": {
                "sha256": _sha256(alien_plants_autogamy_html)
            },
            f"direct_literature/{direct_literature_csv.name}": {
                "sha256": _sha256(direct_literature_csv)
            },
            f"baseline/{current_lineages_csv.name}": {"sha256": _sha256(current_lineages_csv)},
            f"baseline/{current_coverage_csv.name}": {"sha256": _sha256(current_coverage_csv)},
        },
        "source_access": {
            "kew_grassbase": "https://static1.kew.org/data/grasses-db/sppindex.htm",
            "nhm_adept": "https://data.nhm.ac.uk/dataset/angiosperm-functional-traits-extracted-from-botanical-descriptions",
            "baseflor": "https://www.tela-botanica.org/ressources/donnees/telechargements/",
            "florabase": "https://florabase.dbca.wa.gov.au/",
            "floraweb_snapshot": "https://github.com/gcol33/taxifydb/releases/download/scrape-snapshots-2026.06/floraweb_raw_2026-06-24.csv",
            "pfaf": "https://pfaf.org/",
            "ken_fern": [
                "https://tropical.theferns.info/",
                "https://temperate.theferns.info/",
            ],
            "tree_of_sex": "https://datadryad.org/dataset/doi:10.5061/dryad.v1908",
            "alien_plants_greece": "https://www.alienplants.gr/pollination-type/autogamy",
        },
        "promotion_performed": False,
        "strict_exclusions": [
            "source pairs already represented by direct evidence",
            "NHM sex system and reward outside strict axes",
            "NHM pollination outside strict structural and reproductive axes",
            "Baseflor sexual system outside strict reproductive assurance",
            "Baseflor non-autogamous pollen-vector values outside strict axes",
            "grass bract glume lemma and fruit colours",
            "cultivar hybrid and non-species ranks",
            "PFAF apomixis and dioecy category conflicts",
            "Ken Fern cultivated-only and family-mismatched records",
            "Tree of Sex PFAF redistributions and non-exact family matches",
        ],
    }
    (output_dir / "scale_source_package_summary.json").write_text(
        json.dumps(summary, indent=2, ensure_ascii=False, sort_keys=True) + "\n",
        encoding="utf-8",
    )
    return summary


