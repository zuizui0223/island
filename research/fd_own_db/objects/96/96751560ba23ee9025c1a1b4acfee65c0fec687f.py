#!/usr/bin/env python3
"""Design check: can E1/E2 tell lineage co-occurrence from trait matching, and with how many archipelagos?

Writes results/20261125_range_map_nectarivore_design/{sim.json,README.md}. Synthetic data only.
"""
import argparse
import json
import pathlib

import numpy as np

from fd.nectarivore_sim import fit_e1_e2, simulate

CASES = [("none", 1.0), ("cooccurrence", 1.0), ("matching", 0.5), ("matching", 1.0)]
GROUPS = (6, 15, 30, 60)


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--out", type=pathlib.Path, default=pathlib.Path("results/20261125_range_map_nectarivore_design"))
    p.add_argument("--reps", type=int, default=40)
    p.add_argument("--boot", type=int, default=99)
    a = p.parse_args()
    a.out.mkdir(parents=True, exist_ok=True)
    rows = []
    for scen, s in CASES:
        for g in GROUPS:
            e1, e2 = [], []
            for r in range(a.reps):
                d = simulate(scen, g, strength=s, seed=10_000 * g + r)
                f = fit_e1_e2(d, n_boot=a.boot, seed=r)
                e1.append(f["share"])
                e2.append(f["residual"])
            e1, e2 = np.array(e1), np.array(e2)
            rows.append(
                {
                    "scenario": scen,
                    "strength": s,
                    "groups": g,
                    "reps": a.reps,
                    "E1_mean": float(np.nanmean(e1[:, 0])),
                    "E2_mean": float(np.nanmean(e2[:, 0])),
                    "E1_positive_rate": float(np.mean(e1[:, 1] > 0)),
                    "E2_positive_rate": float(np.mean(e2[:, 1] > 0)),
                }
            )
            print(json.dumps(rows[-1]), flush=True)
    (a.out / "sim.json").write_text(json.dumps(rows, indent=2))
    lines = [
        "# Design check: lineage co-occurrence vs trait matching (synthetic data)",
        "",
        "Generated by `scripts/nectarivore_identifiability_sim.py` "
        f"({a.reps} replicates per cell, {a.boot} group-bootstrap draws, 8 islands per archipelago).",
        "Positive rate = share of replicates whose 95 % group-bootstrap interval lies above 0.",
        "No real data is used. See `docs/RANGE_MAP_NECTARIVORE_CONTRACT_20261125.md`.",
        "",
        "| Scenario | Strength | Archipelagos | Mean E1 | Mean E2 | E1 > 0 rate | E2 > 0 rate |",
        "|---|---:|---:|---:|---:|---:|---:|",
    ]
    for r in rows:
        lines.append(
            f"| {r['scenario']} | {r['strength']} | {r['groups']} | {r['E1_mean']:+.3f} | {r['E2_mean']:+.3f} | "
            f"{r['E1_positive_rate']:.2f} | {r['E2_positive_rate']:.2f} |"
        )
    (a.out / "README.md").write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
